	<h2>Det køber du</h2>
	<p>
		Fakturapakken version 1.0 er en digital ZIP-fil med fire redigerbare Word-skabeloner (faktura
		med moms, faktura uden moms, tilbud og kreditnota), en Excel-fil med fem ark, en Word-guide, en
		Word-tekst til venlig betalingspåmindelse og en læs-mig-fil.
	</p>
	<p>
		Word-skabelonerne beregner ikke beløb automatisk. Excel-filen indeholder formler. Du skal bruge
		et program, der understøtter .docx og .xlsx; softwarelicenser medfølger ikke. Layout og formler
		kan variere mellem programmer. Pakken indeholder ikke makroer.
	</p>
	<h2>Pris og betaling</h2>
	<p>
		Prisen er 99 DKK inklusive 25% moms (79,20 kr. eksklusive moms og 19,80 kr. moms). Du betaler én
		gang via Stripe. Der oprettes ikke et abonnement, og der sker ingen automatisk fornyelse. Den
		samlede pris vises inden din betaling.
	</p>
	<h2>Levering og adgang</h2>
	<p>
		Du skal logge ind eller oprette en konto før betaling. Når betalingen er bekræftet af
		betalingsudbyderen, kan du hente pakken under Mine køb. Bekræftelsen kan tage et øjeblik. En
		returadresse fra betalingssiden er ikke i sig selv bevis for et gennemført køb.
	</p>
	<p>
		Hvis betalingen er gennemført, men filerne ikke bliver tilgængelige, skal du kontakte os. Køb
		ikke pakken igen for at løse et leveringsproblem. Gem filerne og en separat backup, når du har
		hentet dem.
	</p>
	<h2>Brugsret</h2>
	<p>
		Du må tilpasse og genbruge filerne til din egen virksomhed og sende udfyldte dokumenter til dine
		kunder og din bogholder. Du må ikke videresælge eller distribuere de tomme skabeloner som et
		produkt. Købet omfatter de leverede filer i version 1.0, ikke cloud-opbevaring, abonnement,
		personlig rådgivning eller løfte om nye versioner og fremtidig adgang til hjemmesiden.
	</p>
	<h2>Fortrydelse for forbrugere</h2>
	<p>
		Som forbruger har du 14 dages fortrydelsesret fra aftalens indgåelse. Vi kræver ikke, at du
		opgiver denne ret for at downloade filerne. Send os en utvetydig besked om, at du vil fortryde
		købet, inden fristen, fx via e-mail med din købsdato og kontoadresse. Undlad at sende
		kortoplysninger.
	</p>
	<p>
		Ved gyldig fortrydelse tilbagebetaler vi beløbet uden unødig forsinkelse og senest 14 dage efter
		din besked via samme betalingsmiddel, medmindre andet aftales. Du skal stoppe brugen og slette
		dine kopier efter fortrydelsen. For erhvervskøb gælder der ikke en lovbestemt fortrydelsesret.
	</p>
	<h2>Fejl og reklamation</h2>
	<p>
		Kontakt os, hvis filerne er beskadigede, ikke kan åbnes som beskrevet eller ikke svarer til det
		købte. Vi undersøger problemet og sørger for afhjælpning eller de øvrige løsninger, du har ret
		til efter gældende lov. Dine ufravigelige forbrugerrettigheder begrænses ikke af disse
		betingelser.
	</p>
	<h2>Dit ansvar og bogføring</h2>
	<p>
		Du skal kontrollere dokumenternes oplysninger, beregninger, momshåndtering og fortløbende
		fakturanummerering før brug. Skabelonerne og generatoren er ikke et bogføringssystem og
		erstatter ikke eventuelle krav om digital bogføring. Ved særlige moms- og skatteforhold bør du
		få konkret rådgivning.
	</p>
	<h2>Klage og lovvalg</h2>
	<p>
		Kontakt os først, så vi kan forsøge at løse problemet. Forbrugere kan, hvis betingelserne og
		beløbsgrænserne er opfyldt, klage gennem <a href="https://naevneneshus.dk/">Nævnenes Hus</a>.
		Dansk ret gælder med respekt for ufravigelige forbrugerrettigheder.
	</p>
