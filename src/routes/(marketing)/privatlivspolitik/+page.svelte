	<h2>Den gratis generator</h2>
	<p>
		Din fakturakladde og din lokale nummerserie gemmes i browserens lokale lager. Den almindelige
		PDF genereres i browseren. Kladden synkroniseres ikke mellem enheder. Rydder du browserdata
		eller mister adgangen til enheden, kan kladden gå tabt. Gem selv dine færdige PDF-filer og
		backup.
	</p>
	<p>
		Et CVR-opslag sender det indtastede CVR-nummer til vores opslagstjeneste og den relevante
		dataleverandør for at hente virksomhedsoplysninger. Derfor er CVR-opslag ikke en
		offline-funktion. Undlad at indtaste CPR-numre eller andre unødvendige personoplysninger.
	</p>
	<h2>Konto, køb og support</h2>
	<p>
		Ved oprettelse behandler vi din e-mailadresse, eventuelt navn, adgangskode i beskyttet form og
		sessionsoplysninger for at levere din konto og adgang til købte filer. Ved køb behandler vi
		produkt, beløb, betalingsstatus og betalingsudbyderens reference. Kortoplysninger håndteres af
		Stripe og gemmes ikke som kortnumre hos os. Ved support behandler vi de oplysninger, du sender
		os.
	</p>
	<p>
		Formål og retsgrundlag er at opfylde aftalen med dig (GDPR artikel 6, stk. 1, litra b),
		overholde bogføringspligter (litra c) og beskytte tjenestens sikkerhed og håndtere relevante
		driftsproblemer (vores legitime interesse, litra f).
	</p>
	<h2>Leverandører</h2>
	<p>
		Vi bruger Cloudflare til hosting og netværksdrift, en hostet Postgres-database til konto- og
		købsdata, Autumn og Stripe til betalingsadministration og Maileroo til transaktionsmails. Google
		Analytics bruges kun til valgfri statistik. Leverandører kan behandle data uden for EU/EØS; hvor
		relevant anvendes de påkrævede overførselsgrundlag, fx standardkontraktbestemmelser eller en
		gældende tilstrækkelighedsafgørelse. Vi sælger ikke dine personoplysninger.
	</p>
	<h2>Statistik og lokalt lager</h2>
	<p>
		Valgfri produktstatistik sendes kun, når du har accepteret analyse. Den kan omfatte
		sidevisninger, PDF-downloads og trin i købsforløbet, men ikke indholdet af dine fakturaer eller
		kunders navne og adresser. Du kan afvise valgfri analyse og stadig bruge generatoren og købe
		pakken. Se <a href="/cookiepolitik/">cookiepolitikken</a>.
	</p>
	<h2>Opbevaring</h2>
	<p>
		Lokale kladder bliver i browseren, indtil du eller browseren sletter dem. Kontooplysninger
		opbevares, mens kontoen er i brug, eller indtil du beder om sletning, med forbehold for
		nødvendige lovlige formål. Bogføringsrelevante købsoplysninger opbevares som udgangspunkt i fem
		år fra udgangen af det relevante regnskabsår. Supportoplysninger gemmes kun, så længe de er
		nødvendige for sagen og eventuelle retskrav.
	</p>
	<h2>Dine rettigheder</h2>
	<p>
		Du kan kontakte os om indsigt, rettelse, sletning, begrænsning, indsigelse og dataportabilitet,
		hvor betingelserne er opfyldt. Tilbagetrækning af analysesamtykke ændrer ikke lovligheden af
		tidligere behandling. Du kan klage til <a href="https://www.datatilsynet.dk/">Datatilsynet</a>.
		Vi kan være nødt til at kontrollere din identitet før udlevering eller sletning af kontodata.
	</p>
